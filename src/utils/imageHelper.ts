/**
 * Resolves product and storefront images seamlessly across dev, preview, and Vercel production.
 * Large bundled JPGs are converted to WebP files before the app starts or builds.
 */
export function resolveImageUrl(url?: string | null): string {
  if (!url) {
    return fallbackImage;
  }

  if (url.startsWith('data:')) return url;

  let imagePath = url;
  if (url.startsWith('http://') || url.startsWith('https://')) {
    try {
      const parsed = new URL(url);
      if (typeof window === 'undefined' || parsed.origin !== window.location.origin) return url;
      imagePath = parsed.pathname;
    } catch {
      return url;
    }
  }

  const filename = imagePath.split('/').pop()?.split('?')[0] || '';
  if (filename && staticImageMap[filename]) {
    return staticImageMap[filename];
  }

  if (imagePath.startsWith('/src/assets/images/')) {
    return `/images/${filename}`;
  }

  return imagePath;
}

/** Returns responsive WebP candidates only for bundled images generated by the build script. */
export function getResponsiveImageSrcSet(url?: string | null): string | undefined {
  if (!url || url.startsWith('data:')) return undefined;

  let imagePath = url;
  if (url.startsWith('http://') || url.startsWith('https://')) {
    try {
      const parsed = new URL(url);
      if (typeof window === 'undefined' || parsed.origin !== window.location.origin) return undefined;
      imagePath = parsed.pathname;
    } catch {
      return undefined;
    }
  }

  const filename = imagePath.split('/').pop()?.split('?')[0] || '';
  const widths = responsiveWidths[filename];
  if (!widths) return undefined;

  const baseName = filename.replace(/\.jpg$/i, '');
  return widths
    .map((width) => `/optimized/${baseName}-${width}.webp ${width}w`)
    .join(', ');
}
